    public static Image MakeBarcodeImage(string InputData, string overCaption = "", string underCaption = "", Font fnt = null)
    {
      if (fnt == null)
        fnt = BarCode128.CaptionFont;
      int[] codes = new Code128Content(InputData).Codes;
      BarCode128.CodeGraphic = Graphics.FromImage(BarCode128.CodeImage);
      SizeF sizeF1 = BarCode128.CodeGraphic.MeasureString(overCaption, fnt);
      SizeF sizeF2 = BarCode128.CodeGraphic.MeasureString(underCaption, fnt);
      int num1 = checked (BarCode128.LabelSize.Height - (BarCode128.Margins1.Height + (int) Math.Round((double) sizeF1.Height) + (int) Math.Round((double) sizeF2.Height) + BarCode128.Margins2.Height));
      BarCode128.CodeImage = (Image) new Bitmap(BarCode128.LabelSize.Width, BarCode128.LabelSize.Height);
      BarCode128.CodeGraphic = Graphics.FromImage(BarCode128.CodeImage);
      BarCode128.CodeGraphic.FillRectangle(Brushes.White, 0, 0, BarCode128.LabelSize.Width, BarCode128.LabelSize.Height);
      //BarCode128.CodeGraphic.DrawString(overCaption, fnt, Brushes.Black, (float) (((double) BarCode128.LabelSize.Width - (double) sizeF1.Width) / 2.0), (float) BarCode128.Margins1.Height);
      BarCode128.CodeGraphic.DrawString(underCaption, fnt, Brushes.Black, (float) (((double) BarCode128.LabelSize.Width - (double) sizeF2.Width) / 2.0), (float) ((double) BarCode128.LabelSize.Height - ((double) sizeF1.Height + (double) BarCode128.Margins2.Height) + (2.0)));
      int num2 = checked (BarCode128.Margins1.Width * BarCode128.BarWeight);
      int index1 = 0;
      while (index1 < codes.Length)
      {
        int index2 = codes[index1];
        int index3 = 0;
        while (index3 < 8)
        {
          int num3 = checked (BarCode128.cPatterns[index2, index3] * BarCode128.BarWeight);
          int num4 = checked (BarCode128.cPatterns[index2, index3 + 1] * BarCode128.BarWeight);
          if (num3 > 0)
            BarCode128.CodeGraphic.FillRectangle(Brushes.Black, (float) num2, (float) BarCode128.Margins1.Height + sizeF1.Height, (float) num3, (float) num1);
          checked { num2 += num3 + num4; }
          checked { index3 += 2; }
        }
        checked { ++index1; }
      }
      return BarCode128.CodeImage;
    }
